def clean_lecturer_name(full_name: str) -> str:
    """Membersihkan gelar depan dan belakang untuk menghasilkan nama inti."""
    # Daftar pola gelar depan yang dihapus
    text = full_name
    front_titles = [
        r"^Prof\.\s*", r"^Dr\.\s*", r"^Drs\.\s*", r"^H\.\s*", r"^Hj\.\s*",
        r"^Prof\s*", r"^Dr\s*", r"^Drs\s*"
    ]
    for _ in range(4):  # Loop berulang untuk gelar bertingkat (misal: Prof. Dr. H.)
        for pat in front_titles:
            text = re.sub(pat, "", text, flags=re.IGNORECASE).strip()

    # Potong gelar belakang setelah tanda koma pertama
    if "," in text:
        text = text.split(",")[0].strip()

    # Hilangkan spasi berlebih
    text = re.sub(r"\s+", " ", text).strip()
    return text


def get_curated_lecturers():
    """Menghasilkan list dosen lengkap dengan full_name, clean_name, dan alias khusus."""
    lecturers = []
    for full in RAW_LECTURERS:
        clean = clean_lecturer_name(full)
        alias = None
        # Tambahkan alias khusus jika ada
        if "Abdurrohman Kasdi" in clean:
            alias = "Prof Dur"

        lecturers.append({
            "full_name": full,
            "clean_name": clean,
            "alias": alias,
        })
    return lecturers
